def _f(x, nd=1):
    if x is None:
        return "-"
    try:
        if not np.isfinite(x):
            return "inf"
    except TypeError:
        return str(x)
    return f"{x:.{nd}f}"


def _rel(p):
    p = Path(p)
    try:
        return str(p.relative_to(REPO_ROOT))
    except ValueError:
        return str(p)


