def v2_section(results, names, lugs, coll, summary):
    """Compare against the CURRENT designs/pack_5200/frame.yaml (v2: straight stays, carbon-wrapped joints,
    1.5 mm formed lumbar pan), which another FEA run produced while this study ran on the v1 snapshot."""
    import yaml
    doc = yaml.safe_load((REPO_ROOT / "designs" / "pack_5200" / "frame.yaml").read_text())
    mg = doc.get("mass_g", {})
    tot = doc.get("mass_total_g")
    if not tot or tot >= 1000:
        return []
    wraps = next((v for k, v in mg.items() if k.startswith("carbon wraps")), None)
    plate = next((v for k, v in mg.items() if k.startswith("lumbar plate")), None)
    boots = mg.get("foot boots (2)", 28.0)
    piv = mg.get("Ti hipbelt pivot insert", 28.0)
    g = lambda n: lugs[(n, "slm_ti")]["mass_g"] * lugs[(n, "slm_ti")]["qty"] if (n, "slm_ti") in lugs else 0.0
    joints_ti = g("crown_corner") + g("stay_hub") + coll["mass_ti_g"] * 2
    rows = [("hubs + crown corners + stay-top collars", wraps, joints_ti),
            ("foot boots (2)", boots, g("stay_foot")),
            ("hipbelt pivot mount", piv, g("hip_pivot_mount"))]
    L = ["## 0. Against the CURRENT frame (v2, " + f"{tot:.0f} g" + ")", "",
         "While this study ran (on the v1 frame.yaml snapshot, 1103 g, 7075 sleeves), the frame was re-sized to the "
         "HA-LS-1 standard: straight stays (no lumbar elbow), **carbon-wrapped tube-to-tube joints** "
         f"({wraps:.0f} g for every hub, corner and collar) and a 1.5 mm formed lumbar pan ({plate:.0f} g). Against v2:", "",
         "| item | v2 (current frame.yaml) | printed Ti (this study) | delta |", "|---|---|---|---|"]
    for lab, a, b in rows:
        if a is None:
            continue
        L.append(f"| {lab} | {a:.0f} g | {b:.0f} g | {b - a:+.0f} g |")
    pv2 = results.get("plate_v2")
    plate_txt = ""
    if pv2 and plate:
        okp = [p for p in pv2 if p["chk"]["min_sf_membrane"] >= 1.0 and p["chk"]["min_sf_buckling"] >= 1.5]
        bb = max(pv2, key=lambda p: p["chk"]["min_sf_buckling"])
        plate_txt = ("The same 2D SIMP run on the v2 1.5 mm pan web (cut-outs between the flanges) FAILS: web "
                     f"buckling SF/req {bb['chk']['min_sf_buckling']:.2f} (need 1.5) with {bb['dxf']['n_cutouts']} "
                     "cut-outs, so the thin formed pan stays solid; the cut-out plate below applies to a flat "
                     "3-4 mm plate only. " if not okp else "")
        if okp:
            b = min(okp, key=lambda p: p["mass_g"])
            flange = 2 * 250 * 25 * 1.5 * 1.55e-3
            L.append(f"| lumbar pan web cut-outs (1.5 mm, {b['dxf']['n_cutouts']} cut-outs) | {plate:.0f} g | "
                     f"{b['mass_g'] + flange:.0f} g | {b['mass_g'] + flange - plate:+.0f} g |")
    L += ["", "**So, for the v2 frame: keep the carbon wraps at the hubs and corners** (printed Ti lugs are heavier "
          "than a 0.75 mm wrap; they win only against metal sleeves). Printed titanium earns its place where a wrap "
          "cannot go: the hipbelt pivot mount and the foot boot / shelf-pivot clevis (compare the rows above), and "
          "as a build aid: the PAHT-CF lugs are an accurate, jig-free way for a first-time builder to assemble the "
          "first prototype frame before learning to wrap. " + plate_txt, ""]
    return L
