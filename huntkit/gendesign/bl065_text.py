         f"| **real margin** (min of the two above) | **{_f(v['real_margin']['static_cinch'])}** | "
         f"**{_f(v['real_margin']['cinch_cycled'])}** |",
         f"| record model as is (no wearer, top free; support artefact) | {_f(s['record_model_free'])} | "
         f"{_f(c['record_model_free'])} |",
