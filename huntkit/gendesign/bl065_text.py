         f"closer ({_f(ub['margin_record'])} vs section {_f(ub['margin_section'])}): end fixity (1/K^2 = "
         f"{1 / ub['K_eff_unbraced'] ** 2:.2f}) outweighs the flat section's 0.81 x I.",
         f"- Side-squeeze {rec['squeeze']['Q_per_side_n']:.0f} N a side: {_f(rec['squeeze']['braced_margin'])} "
