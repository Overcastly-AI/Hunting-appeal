"""CLI for huntkit.manufacturing.

    python -m huntkit.manufacturing.cli fields                       # contract fields of SewingOp and BOMLine
    python -m huntkit.manufacturing.cli techpack spec.json out.pdf   # render a tech pack from a JSON spec
    python -m huntkit.manufacturing.cli check spec.json              # list missing contract sections

The JSON spec is ``TechPack`` as a dict: title, subtitle, date, footer, cover [[k, v]], contents, sections
[{title, blocks: [{kind: p|h2|table|image|space|break, ...}]}] (see huntkit/manufacturing/techpack.py).
Product packages are generated by their own scripts, e.g. ``python designs/pack_5200/mfg_corrie_f_rev3.py``.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import BOM_LINE_FIELDS, SEWING_OP_FIELDS, TechPack, missing_sections, tech_pack


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m huntkit.manufacturing.cli", description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("fields", help="print the SewingOp / BOMLine fields")
    t = sub.add_parser("techpack", help="render a tech pack PDF from a JSON spec")
    t.add_argument("spec")
    t.add_argument("out")
    t.add_argument("--strict", action="store_true", help="fail if a contract section is missing")
    c = sub.add_parser("check", help="list the contract sections a JSON spec lacks")
    c.add_argument("spec")
    a = ap.parse_args(argv)
    if a.cmd == "fields":
        print(json.dumps({"SewingOp": SEWING_OP_FIELDS, "BOMLine": BOM_LINE_FIELDS}, indent=1))
        return 0
    d = TechPack.from_dict(json.loads(Path(a.spec).read_text()))
    if a.cmd == "check":
        miss = missing_sections(d)
        print(json.dumps({"missing": miss}))
        return 1 if miss else 0
    p = tech_pack(d, a.out, strict=a.strict)
    print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
